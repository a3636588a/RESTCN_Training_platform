// ===== Python-equivalent constants =====
// From your python (defaults):
//   MIN_SPAN_B = 500
//   gain clamp = [0.5, 2.5]
//   release target delta = 600
//   release eval N = 3
//   release max step ratio = 0.20
//   release clamp = [1.0, 1.8]

#ifndef GAINMAP_EPS
#define GAINMAP_EPS                 (1e-6f)
#endif

#define MIN_SPAN_B                  (500.0f)
#define GAIN_CLAMP_MIN              (0.5f)
#define GAIN_CLAMP_MAX              (2.5f)

#define RELEASE_TARGET_DELTA        (600.0f)
#define RELEASE_MAX_STEP_RATIO      (0.20f)
#define RELEASE_GAIN_MIN            (1.0f)
#define RELEASE_GAIN_MAX            (1.8f)

// ---- Standard glove A spans (MUST match your python constants) ----
// These values are now provided via extern from mlp_features_lib.c
// to guarantee a single unified definition generated by UI.

static float clampf(float x, float lo, float hi)
{
    if (x < lo) return lo;
    if (x > hi) return hi;
    return x;
}

void gainmap_init(gain_map_t *gm)
{
    if (!gm) return;

    for (uint8_t ch = 0; ch < GAIN_CHN; ch++)
    {
        gm->g[ch] = 1.0f;
        gm->rel_len[ch] = 0;
        gm->rel_idx[ch] = 0;
        for (uint8_t i = 0; i < RELEASE_EVAL_N; i++)
        {
            gm->rel_hist[ch][i] = 0.0f;
        }
    }
    gm->ready = false;
}

bool gainmap_is_ready(const gain_map_t *gm)
{
    return (gm && gm->ready);
}

float gainmap_get(const gain_map_t *gm, uint8_t ch)
{
    if (!gm || ch >= GAIN_CHN) return 1.0f;
    return gm->g[ch];
}

// median for n=1..3
static float median_upto3(const float *a, uint8_t n)
{
    float x0 = a[0];
    float x1 = (n > 1) ? a[1] : a[0];
    float x2 = (n > 2) ? a[2] : a[0];

    // sort 3
    if (x0 > x1) { float t = x0; x0 = x1; x1 = t; }
    if (x1 > x2) { float t = x1; x1 = x2; x2 = t; }
    if (x0 > x1) { float t = x0; x0 = x1; x1 = t; }

    if (n == 1) return x0;
    if (n == 2) return 0.5f * (x0 + x1);
    return x1;
}

/**
 * Python-equivalent main mapping:
 *   span_a = STD_HOLDAVG_A[ch] - STD_BASELINE_A[ch]
 *   span_b = HOLDAVG_B[ch] - MOVBASE_B[ch]
 *   span_b_eff = max(abs(span_b), MIN_SPAN_B=500)
 *   g = span_a / span_b_eff
 *   clamp g to [0.5, 2.5]
 */
bool gainmap_update_from_holdavg(gain_map_t *gm,
                                 const uint16_t holdavg_b[GAIN_CHN],
                                 const uint16_t movbase_b[GAIN_CHN])
{
    if (!gm || !holdavg_b || !movbase_b) return false;

    bool updated = false;

    for (uint8_t ch = 0; ch < GAIN_CHN; ch++)
    {
        const float span_a = (float)((int)STD_HOLDAVG_A_U16[ch] - (int)STD_BASELINE_A_U16[ch]);
        if (span_a <= 0.0f) continue;

        const float base_b = (float)movbase_b[ch];
        const float hold_b = (float)holdavg_b[ch];
        const float span_b = hold_b - base_b;

        float span_b_eff = fabsf(span_b);
        if (span_b_eff < MIN_SPAN_B) span_b_eff = MIN_SPAN_B;

        float g_new = span_a / (span_b_eff + GAINMAP_EPS);
        g_new = clampf(g_new, GAIN_CLAMP_MIN, GAIN_CLAMP_MAX);

        if (fabsf(g_new - gm->g[ch]) > GAINMAP_EPS)
        {
            gm->g[ch] = g_new;
            updated = true;
        }
    }

    gm->ready = true;
    return updated;
}

/**
 * Python-equivalent RELEASE tune:
 *   d_mapped = (rel_avg - base) * g
 *   keep last 3 values -> median
 *   if median < 600:
 *       need = 600 / median
 *       step = min(need-1, 0.20)
 *       g *= (1+step)
 *   clamp g:
 *       global [0.5, 2.5]
 *       release [1.0, 1.8]
 *
 * IMPORTANT: only tunes upward (never reduces g).
 */
bool gainmap_tune_from_release(gain_map_t *gm,
                               const uint16_t rel_avg[GAIN_CHN],
                               const uint16_t movbase_b[GAIN_CHN])
{
    if (!gm || !rel_avg || !movbase_b) return false;
    if (!gm->ready) return false;  // align with python: tune after mapping ready

    bool tuned_any = false;
    const float T = RELEASE_TARGET_DELTA;
    const float eps = 1e-6f;

    for (uint8_t ch = 0; ch < GAIN_CHN; ch++)
    {
        float g = gm->g[ch];
        g = clampf(g, GAIN_CLAMP_MIN, GAIN_CLAMP_MAX);

        const float rel  = (float)rel_avg[ch];
        const float base = (float)movbase_b[ch];
        const float d_rel = rel - base;

        // mapped delta in A-scale
        const float d_mapped = d_rel * g;

        // push into ring history
        uint8_t idx = gm->rel_idx[ch];
        gm->rel_hist[ch][idx] = d_mapped;
        gm->rel_idx[ch] = (uint8_t)((idx + 1u) % RELEASE_EVAL_N);
        if (gm->rel_len[ch] < RELEASE_EVAL_N) gm->rel_len[ch]++;

        // copy and compute median (n <= 3)
        float tmp[RELEASE_EVAL_N];
        for (uint8_t i = 0; i < gm->rel_len[ch]; i++)
        {
            tmp[i] = gm->rel_hist[ch][i];
        }
        const float d_est = median_upto3(tmp, gm->rel_len[ch]);

        if (d_est >= T) continue;

        const float denom = (d_est > eps) ? d_est : eps;
        const float need = T / denom;       // > 1
        float step = need - 1.0f;           // desired increment
        if (step > RELEASE_MAX_STEP_RATIO) step = RELEASE_MAX_STEP_RATIO;
        if (step <= 0.0f) continue;

        float g_new = g * (1.0f + step);

        // clamps (same as python)
        g_new = clampf(g_new, GAIN_CLAMP_MIN, GAIN_CLAMP_MAX);
        g_new = clampf(g_new, RELEASE_GAIN_MIN, RELEASE_GAIN_MAX);

        // tune is upward-only; if clamp made it <= current, skip
        if (g_new > g + 1e-12f)
        {
            gm->g[ch] = g_new;
            tuned_any = true;
        }
        else
        {
            // keep stored clamped g
            gm->g[ch] = g;
        }
    }

    return tuned_any;
}

/**
 * Apply gain to delta only:
 *   row' = base + (row-base)*g
 * This is what you want before feeding MLP features.
 */
uint16_t gainmap_apply_row_u16(const gain_map_t *gm,
                               uint8_t ch,
                               uint16_t row,
                               uint16_t movbase)
{
    float g = 1.0f;
    if (gm && gm->ready && (ch < GAIN_CHN))
    {
        g = gm->g[ch];
    }

    const float base = (float)movbase;
    const float x    = (float)row;

    float y = base + (x - base) * g;

    if (y < 0.0f) y = 0.0f;
    if (y > 65535.0f) y = 65535.0f;

    return (uint16_t)(y + 0.5f);
}
